/**
 * THE demo dataset (Shared Contract v2, section 9). Plain data only: no functions, no imports of runtime code.
 *
 * Used by the scan app's mock, the 3D map's mock and (translated) backend seed/demo.sql, so IDs must stay put.
 * Zone and opening IDs are the canonical ones: seed/building.sql should reuse them.
 *
 * Generated once, then hand-editable. Rules this file follows:
 *  - shelves A1, A2, B1, F1 at the contract positions and rotations (positions are made up)
 *  - decks 1 in thick, G deck top at 4 in, rows evenly spaced
 *  - includes: a part in two slots (SB-12-BV), a slot holding two parts (A2-G-1), a part with no location
 *    (SW-FLOAT-01), a part at 0 on hand (PVC-3-SAN), a part over par (DUCT-6-COLLAR, FLT-20X20X1),
 *    leading zeros (00417-B), and dimensions that do not fit the bin (WH-ANODE-34 in A1-G-4).
 */
